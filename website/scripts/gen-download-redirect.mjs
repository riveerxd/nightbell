#!/usr/bin/env node
/**
 * Writes the one line of Nginx configuration that has a version number in it.
 *
 *   node scripts/gen-download-redirect.mjs            # write the snippet
 *   node scripts/gen-download-redirect.mjs --check    # fail if it is stale
 *
 * ## Why this is generated and not typed
 *
 * `/download` 302s to the APK on GitHub, and the URL of that APK contains the
 * release version twice. That makes it the fourth place a version lives, after
 * `site.config.mjs`, the release tag and the asset filename, and the first three
 * are already documented as needing to be updated together.
 *
 * A fourth copy in a file that lives on a different machine, is deployed by hand,
 * and is never touched during a release, is not a copy that stays correct. It
 * would go stale at the next version bump and the failure would be silent in the
 * worst possible way: the button keeps working, because the old GitHub URL keeps
 * resolving forever, so the site would quietly serve the previous release to
 * everybody who used the button while the page around it advertised the new one.
 *
 * So the snippet is derived from `site.config.mjs` and `--check` runs inside
 * `npm run verify`, which `deploy.sh` runs before it uploads anything. Forgetting
 * to regenerate it is now a failed deploy rather than a wrong download.
 *
 * ## What is not generated
 *
 * The `location = /download` block itself, which is hand-written in
 * `deploy/nginx/nightbell.app.conf`. It has no version in it and never changes,
 * and generating a whole server block from here would mean this script owning the
 * TLS paths and the cache tiers, which is a much larger thing to be responsible
 * for than one `return`.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RELEASE, DOWNLOAD_PATH } from '../site.config.mjs';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(SITE, 'deploy/nginx/snippets/nightbell/download-target.conf');
const REL = 'deploy/nginx/snippets/nightbell/download-target.conf';

const CHECK = process.argv.includes('--check');

/**
 * 302 and not 301, which is the whole reason this file needs a comment.
 *
 * A 301 is permanent and browsers are entitled to cache it forever without
 * revalidating. Ship one here and every visitor who clicked the button on 3.0.4
 * keeps being sent to the 3.0.4 APK after 3.0.5 is out, from their own disk,
 * with no request to this server that could correct them or even reveal that it
 * is happening. The redirect target changes every release by design, which is the
 * textbook definition of temporary.
 */
const body = `# Generated by scripts/gen-download-redirect.mjs. Do not edit.
#
# The target of ${DOWNLOAD_PATH}, regenerated from RELEASE in site.config.mjs on every
# build and checked by \`npm run verify\`, so it cannot fall behind a release.
#
# 302 rather than 301: this target changes with every version, and a permanent
# redirect would be cached in browsers past the next release with no request
# reaching this server to correct it.
#
# Included from the \`location = ${DOWNLOAD_PATH}\` block. It sets the caching and the
# logging; this file only says where the click goes.
#
#   version   ${RELEASE.version}
#   asset     ${RELEASE.apkName}
return 302 ${RELEASE.apkUrl};
`;

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error(`Missing ${REL}. Run \`npm run download-redirect\`.`);
    process.exit(1);
  }
  const have = readFileSync(OUT, 'utf8');
  if (have !== body) {
    console.error(
      [
        `${REL} is stale.`,
        '',
        `It does not match RELEASE ${RELEASE.version} in site.config.mjs, so ${DOWNLOAD_PATH}`,
        'would keep sending people to whichever APK it currently names.',
        '',
        'Fix with:  npm run download-redirect',
        'Then copy the snippet to the box and reload, see deploy/README.md.',
      ].join('\n'),
    );
    process.exit(1);
  }
  console.log(`ok  ${REL} matches RELEASE ${RELEASE.version}`);
  process.exit(0);
}

mkdirSync(dirname(OUT), { recursive: true });
const changed = !existsSync(OUT) || readFileSync(OUT, 'utf8') !== body;
writeFileSync(OUT, body);
console.log(
  changed
    ? `wrote  ${REL}  ->  ${RELEASE.apkName}\n       the snippet changed, so it needs copying to the box (deploy/README.md)`
    : `ok     ${REL} already current for ${RELEASE.version}`,
);
